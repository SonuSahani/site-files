create or replace function public.cast_poll_vote(
  p_poll_id text,
  p_option_id text,
  p_voter_token text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_count int := 0;
begin
  if coalesce(trim(p_poll_id),'') = '' or coalesce(trim(p_option_id),'') = '' or coalesce(trim(p_voter_token),'') = '' then
    return jsonb_build_object('inserted', false, 'reason', 'invalid_input');
  end if;

  insert into public.poll_votes (poll_id, option_id, voter_token)
  values (p_poll_id, p_option_id, p_voter_token)
  on conflict (poll_id, voter_token) do nothing;

  get diagnostics inserted_count = row_count;
  if inserted_count = 0 then
    return jsonb_build_object('inserted', false, 'reason', 'already_voted');
  end if;

  insert into public.poll_vote_totals (poll_id, option_id, votes)
  values (p_poll_id, p_option_id, 1)
  on conflict (poll_id, option_id) do update
    set votes = public.poll_vote_totals.votes + 1;

  return jsonb_build_object('inserted', true);
end;
$$;

grant select, insert on public.poll_votes to anon, authenticated;
