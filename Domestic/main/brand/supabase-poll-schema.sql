-- Poll Hub schema for Supabase
-- Run in Supabase SQL Editor.

create table if not exists public.poll_votes (
  id bigint generated by default as identity primary key,
  poll_id text not null,
  option_id text not null,
  voter_token text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists poll_votes_poll_voter_uidx
  on public.poll_votes (poll_id, voter_token);

create index if not exists poll_votes_poll_idx
  on public.poll_votes (poll_id);

create table if not exists public.poll_vote_totals (
  poll_id text not null,
  option_id text not null,
  votes bigint not null default 0,
  primary key (poll_id, option_id)
);

create index if not exists poll_vote_totals_poll_idx
  on public.poll_vote_totals (poll_id);

insert into public.poll_vote_totals (poll_id, option_id, votes)
select poll_id, option_id, count(*)::bigint
from public.poll_votes
group by poll_id, option_id
on conflict (poll_id, option_id) do update
  set votes = excluded.votes;

create table if not exists public.poll_comments (
  id bigint generated by default as identity primary key,
  poll_id text not null,
  author text not null default 'Guest',
  comment_text text not null,
  visitor_token text,
  created_at timestamptz not null default now()
);

create index if not exists poll_comments_poll_idx
  on public.poll_comments (poll_id, created_at desc);

create table if not exists public.poll_ideas (
  id bigint generated by default as identity primary key,
  question text not null,
  category text not null,
  options jsonb not null default '[]'::jsonb,
  author text not null default 'Anonymous',
  status text not null default 'pending',
  visitor_token text not null,
  created_at timestamptz not null default now()
);

create index if not exists poll_ideas_token_idx
  on public.poll_ideas (visitor_token, created_at desc);

alter table public.poll_votes enable row level security;
alter table public.poll_vote_totals enable row level security;
alter table public.poll_comments enable row level security;
alter table public.poll_ideas enable row level security;

